def _extract_images_endpoint(body: dict) -> list[bytes]:
    blobs = []
    for entry in body.get("data") or []:
        if entry.get("b64_json"):
            blobs.append(base64.b64decode(entry["b64_json"]))
        elif entry.get("url"):
            blobs.append(requests.get(entry["url"], timeout=90).content)
    return blobs


def _extract_chat_endpoint(body: dict) -> list[bytes]:
    blobs = []
    for choice in body.get("choices") or []:
        message = choice.get("message") or {}
        for image in message.get("images") or []:
            url = (image.get("image_url") or {}).get("url")
            if not url:
                continue
            if url.startswith("data:"):
                blobs.append(base64.b64decode(url.split(",", 1)[1]))
            else:
                blobs.append(requests.get(url, timeout=90).content)
    return blobs


def _request_frame(
    model: str,
    prompt: str,
    reference_paths: list[str],
    seed: int,
) -> list[bytes]:
    """Generate one frame, trying the image endpoint then chat completions.

    The two endpoints disagree about how they accept a reference image, and
    which one supports it varies by model. Rather than assume, try both and
    keep whichever returns an actual image.
    """
    refs = [_data_url(p) for p in reference_paths if os.path.exists(p)]
    errors: list[str] = []

    # 1. Dedicated image endpoint.
    if refs:
        payload = {
            "model": model,
            "prompt": prompt,
            "aspect_ratio": "9:16",
            "seed": seed,
            "n": 1,
            "input_references": [{"type": "image_url", "image_url": {"url": r}} for r in refs],
        }
    else:
        payload = {"model": model, "prompt": prompt, "aspect_ratio": "9:16", "seed": seed, "n": 1}

    try:
        resp = _openrouter_post("/images", payload, raw=False, attempts=2)
        blobs = _extract_images_endpoint(resp.json())
        if blobs and len(blobs[0]) > 15_000:
            return blobs[0]
        errors.append("/images returned no usable image")
    except MediaGenerationError as exc:
        errors.append(f"/images: {str(exc)[:140]}")

    # 2. Chat completions multimodal path.
    content: list[dict] = [{"type": "text", "text": prompt}]
    for ref in refs:
        content.append({"type": "image_url", "image_url": {"url": ref}})

    chat_payload = {
        "model": model,
        "messages": [{"role": "user", "content": content}],
        "modalities": ["image", "text"],
    }
    try:
        resp = _openrouter_post("/chat/completions", chat_payload, raw=False, attempts=2)
        body = resp.json()
        blobs = _extract_chat_endpoint(body)
        if blobs and len(blobs[0]) > 15_000:
            return blobs[0]
        errors.append("/chat/completions returned no usable image")
    except MediaGenerationError as exc:
        errors.append(f"/chat/completions: {str(exc)[:140]}")
    except Exception as exc:
        errors.append(f"/chat/completions: {type(exc).__name__}: {str(exc)[:120]}")

    raise MediaGenerationError(f"{model} could not produce a frame: " + " | ".join(errors))


def _motion_prompt(motion_prompt: str, index: int, total: int, amplify: bool = False) -> str:
    """Describe the action as a progression so each step is a small delta."""
    progress = f"({index + 1} of {total} in a continuous shot)"
    if index == 0:
        beat = f"BEGIN the movement: {motion_prompt}"
    elif index >= total - 1:
        beat = f"HOLD and settle at the end of the movement: {motion_prompt}"
    else:
        beat = f"CONTINUE the same movement a fraction further along: {motion_prompt}"
    extra = f" {MOTION_AMPLIFY}" if amplify else ""
    return f"{beat} {progress}{extra}. {STYLE_LOCK}. Do not redraw or restyle the subject."


def _generate_chain(
    still_path: str,
    motion_prompt: str,
    frames_dir: str,
    frame_count: int,
    base_seed: int,
    log,
    amplify: bool = False,
) -> list[str]:
    """Walk the chain and return the ordered list of frame paths."""
    os.makedirs(frames_dir, exist_ok=True)

    anchor_small = os.path.join(frames_dir, "_anchor.jpg")
    _shrink_reference(still_path, anchor_small)

    prev_small = anchor_small
    prev_sig = _luma_signature(still_path)
    anchor_sig = _luma_signature(anchor_small)
    if anchor_sig is None:
        anchor_sig = prev_sig

    order = [
        k.strip()
        for k in os.environ.get("FRAME_PROVIDER_ORDER", DEFAULT_FRAME_ORDER).split(",")
        if k.strip()
    ]
    models = [(k, m) for k, m in billing.filter_ladder(order, FRAME_LADDER, "frame diffusion")]
    if not models:
        # Do not start generating: under the free-only policy this is the
        # expected path, and the caller needs a clear reason to fall back
        # rather than a wall of per-frame billing errors.
        raise FrameDiffusionError(
            "no free image model is permitted, so frame diffusion cannot run "
            "(every FRAME_LADDER entry is a paid OpenRouter model). Characters "
            "will fall back to the free rungs."
        )

    paths: list[str] = []
    # A model that fails on frame 3 should not doom frames 4..N. Remember which
    # rungs proved they work and prefer them for the rest of the chain.
    preferred = models[0][1]
    drift_warnings = 0

    for i in range(frame_count):
        out_path = os.path.join(frames_dir, f"f{i:04d}.jpg")
        prompt = _motion_prompt(motion_prompt, i, frame_count, amplify)

        blob = None
        last_error = None
        for key, model in models:
            if model != preferred:
                continue
            try:
                blob = _request_frame(model, prompt, [anchor_small, prev_small], base_seed + i)
                break
            except MediaGenerationError as exc:
                last_error = exc
        if blob is None:
            # Preferred rung failed; let any rung try, and adopt whichever works.
            for key, model in models:
                if model == preferred:
                    continue
                try:
                    blob = _request_frame(model, prompt, [anchor_small, prev_small], base_seed + i)
                    preferred = model
                    last_error = None
                    log(f"  [fd] frame {i}: fell back to {model}")
                    break
                except MediaGenerationError as exc:
                    last_error = exc
        if blob is None:
            raise FrameDiffusionError(
                f"frame {i + 1}/{frame_count} could not be generated: {last_error}"
            )

        with open(out_path, "wb") as fh:
            fh.write(blob)

        ok, reason = _frame_is_usable(out_path)
        if not ok:
            os.remove(out_path)
            raise FrameDiffusionError(f"frame {i + 1}/{frame_count} unusable: {reason}")

        sig = _luma_signature(out_path)
        delta = _mean_abs(sig, prev_sig)
        drift = _mean_abs(sig, anchor_sig)

        if 0 <= delta < STALL_DELTA:
            # The model returned a byte-for-byte-equivalent picture. Nudge it
            # once with a fresh seed; a genuinely frozen chain is a slideshow.
            log(f"  [fd] frame {i}: stalled (delta {delta:.2f}) - nudging seed")
            try:
                retry = _request_frame(preferred, prompt, [anchor_small, prev_small], base_seed + i + 5000)
                with open(out_path, "wb") as fh:
                    fh.write(retry)
                sig = _luma_signature(out_path)
                delta = _mean_abs(sig, prev_sig)
                drift = _mean_abs(sig, anchor_sig)
            except MediaGenerationError:
                pass

        prev_small_new = os.path.join(frames_dir, f"_prev{i:04d}.jpg")
        _shrink_reference(out_path, prev_small_new)
        prev_small = prev_small_new
        prev_sig = sig
        paths.append(out_path)

        if i % 6 == 0 or i == frame_count - 1:
            log(f"  [fd] frame {i + 1}/{frame_count} (delta {delta:.1f}, drift {drift:.1f})")
        if drift > MAX_DRIFT:
            drift_warnings += 1

    if drift_warnings > frame_count * 0.4:
        log(
            f"  [fd] WARNING: {drift_warnings}/{frame_count} frames drifted far from the anchor - "
            f"the subject may be morphing between frames"
        )

    return paths


