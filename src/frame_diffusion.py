"""
Frame diffusion: turn a beat still into genuinely moving footage using only
an image-to-image model.

Why this exists
---------------
OpenRouter currently exposes ZERO models with `video` among their
`output_modalities` (verified directly against /api/v1/models), so no amount
of OpenRouter credit can buy an image-to-video model here. Every other route
to motion either costs money the agency does not have (Pollinations bills
video in pollen) or depends on a free GPU tier that saturates (HF ZeroGPU
Spaces - which is exactly why issue #6 shipped dead characters).

What frame diffusion does instead
---------------------------------
An autoregressive image chain. Frame 0 is the validated beat still. Frame i+1
is generated by the same image model conditioned on TWO references:

  1. the ORIGINAL beat still  -> the identity anchor
  2. the previous frame       -> where the motion currently is

plus a motion prompt asking for the action "a fraction further along".
ffmpeg's optical-flow `minterpolate` then fills the gaps up to a 24 fps
delivery frame rate.

Re-anchoring every frame to the original is the whole trick. A naive chain
(previous frame only) compounds its own error, and the character morphs into
a different person within a few frames - which reads as horrifying rather
than animated. Re-anchoring pulls the face back toward the real face on
every step, so drift stays bounded no matter how long the chain runs.

Cost: gemini-2.5-flash-image is ~$0.00003 per image, so an ~11s reel at an
8 fps generation rate is ~90 frames, roughly $0.003. Generation deliberately
runs slower than delivery: generating 24 independent frames per second buys
per-frame noise and shimmer, not extra motion, while tripling the bill.
"""

import base64
import json
import os
import subprocess
import time

import requests

from src.openrouter_media import (
    OPENROUTER_BASE,
    MediaGenerationError,
    _api_key,
    _openrouter_post,
)
import src.billing as billing

FFMPEG_BIN = os.environ.get("FFMPEG_BIN", "ffmpeg")

# Delivery frame rate. The final MP4 is 24 fps regardless of how many frames
# were actually generated.
OUTPUT_FPS = 24

# Generation rate. 8 fps of deliberate motion, interpolated up to 24.
DEFAULT_SOURCE_FPS = 8

# Per-frame sanity bounds, on a 0-255 mean absolute luma difference between the
# 64x112 grayscale signature of two frames.
#
# The stall bound is deliberately near zero. Consecutive generated frames are
# meant to be only a fraction apart, so their delta is naturally tiny and
# almost always above this; a lower bound would "nudge" nearly every frame and
# silently double the API bill. A true duplicate lands at exactly 0.
STALL_DELTA = 0.05

# Cumulative drift from the anchor warns about the opposite failure: the chain
# walking away from the original subject until it morphs into something else.
MAX_DRIFT = 34.0

# Reference images are downscaled before being base64'd. Sending full-res
# 9:16 stills on every one of ~90 requests is pure wasted bandwidth and
# noticeably slower encodes.
REFERENCE_MAX_SIDE = 768

# Ordered ladder, cheapest-and-best first. All three accept image+text input,
# which is the only hard requirement for a re-anchored chain. All three are
# PAID - OpenRouter publishes no free image-output model at all - so under the
# default free-only billing policy every rung is dropped and this provider
# reports itself unavailable rather than spending.
FRAME_LADDER = {
    "gemini_flash": "google/gemini-2.5-flash-image",
    "gpt5_mini": "openai/gpt-5-image-mini",
    "gemini_31": "google/gemini-3.1-flash-image",
}
DEFAULT_FRAME_ORDER = "gemini_flash,gpt5_mini,gemini_31"

# Interpolation rungs, richest first. `{fps}` is substituted.
#
#   mci     - motion-compensated interpolation, real optical flow. Best result,
#             but the aobmc/bidir combination is not reliable across ffmpeg
#             builds (it fails at EOF on ffmpeg 6.x).
#   mci_obb - same motion compensation with the simpler, older OBMC mode.
#   blend   - blends neighbouring frames; no motion estimation, so it cannot
#             fail on "invalid data" and is a safe smooth-looking result.
#   fps     - frame duplication. Always works; last resort so a paid chain is
#             never thrown away over a filter setting.
INTERPOLATION_LADDER = [
    ("mci", "minterpolate=fps={fps}:mi_mode=mci:mc_mode=aobmc:me_mode=bidir:vsbmc=1"),
    ("mci_obb", "minterpolate=fps={fps}:mi_mode=mci:mc_mode=obmc:me_mode=bidir"),
    ("blend", "minterpolate=fps={fps}:mi_mode=blend"),
    ("fps", "fps={fps}"),
]

STYLE_LOCK = (
    "identical framing, identical camera position, identical lighting, "
    "identical wardrobe, identical background, photorealistic, handheld "
    "smartphone video"
)

# Appended on the second attempt when the first chain animated too gently to
# clear the motion gate. Per-frame deltas from a re-anchored image chain are
# inherently gentler than a native video model's output, so the honest fix is
# to ask for a larger physical change - never to lower the gate, because the
# dead-character camera pan sits just underneath it.
MOTION_AMPLIFY = (
    "AMPLIFY the movement: a clearly visible change of pose between each "
    "frame, an obvious head turn and a visible shift of body weight, not a "
    "near-identical frame"
)


class FrameDiffusionError(RuntimeError):
    """No model could produce a coherent frame chain."""


