def _run(cmd: list, timeout: int = 300) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, capture_output=True, timeout=timeout, text=True)


def _shrink_reference(src: str, dst: str) -> str:
    """Downscale a still for use as an in-prompt reference."""
    try:
        from PIL import Image
    except ImportError:
        return src

    try:
        with Image.open(src) as im:
            im = im.convert("RGB")
            w, h = im.size
            scale = REFERENCE_MAX_SIDE / max(w, h)
            if scale >= 1.0:
                im.save(dst, "JPEG", quality=88)
                return dst
            im.resize((max(1, int(w * scale)), max(1, int(h * scale))), Image.LANCZOS).save(
                dst, "JPEG", quality=88
            )
        return dst
    except Exception:
        return src


def _data_url(path: str) -> str:
    with open(path, "rb") as fh:
        encoded = base64.b64encode(fh.read()).decode("ascii")
    ext = os.path.splitext(path)[1].lstrip(".").lower() or "jpeg"
    if ext == "jpg":
        ext = "jpeg"
    return f"data:image/{ext};base64,{encoded}"


def _luma_signature(path: str):
    """Small grayscale fingerprint used for the drift/delta gates."""
    try:
        import numpy as np
        from PIL import Image
    except ImportError:
        return None
    try:
        with Image.open(path) as im:
            arr = np.asarray(im.convert("L").resize((64, 112), Image.LANCZOS)).astype(float)
        return arr
    except Exception:
        return None


def _mean_abs(a, b) -> float:
    if a is None or b is None:
        return -1.0
    import numpy as np

    return float(np.abs(a - b).mean())


def _frame_is_usable(path: str) -> tuple[bool, str]:
    """Cheaper and looser than validate_image: frames are re-cropped by
    ffmpeg anyway, so aspect ratio is not this gate's business."""
    if not os.path.exists(path):
        return False, "frame missing"
    size = os.path.getsize(path)
    if size < 15_000:
        return False, f"frame too small ({size} bytes)"
    try:
        from PIL import Image, ImageStat
    except ImportError:
        return True, "ok (Pillow unavailable)"
    try:
        with Image.open(path) as im:
            im.load()
            w, h = im.size
            if w < 256 or h < 256:
                return False, f"frame too low-res ({w}x{h})"
            stddev = ImageStat.Stat(im.convert("L")).stddev[0]
            if stddev < 10.0:
                return False, f"frame is flat (luma stddev {stddev:.1f})"
    except Exception as exc:
        return False, f"unreadable frame: {exc}"
    return True, "ok"


