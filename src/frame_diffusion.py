def animate_still_to_clip(
    img_path: str,
    motion_prompt: str,
    out_path: str,
    duration: float,
    seed: int = 0,
    log=print,
) -> str:
    """Animate one beat still into a moving MP4. Returns out_path.

    Raises FrameDiffusionError rather than writing a dead clip, so the caller
    can fall through to the next provider rather than shipping a slideshow.
    """
    src_fps = int(os.environ.get("FRAME_SOURCE_FPS", DEFAULT_SOURCE_FPS))
    src_fps = max(2, min(src_fps, 12))
    # +2 frames of headroom. Optical-flow interpolation synthesises frames
    # *between* existing ones and cannot extrapolate past the last, so N input
    # frames only ever yield N-1 intervals - a 3.0s beat rendered from exactly
    # 24 frames came back at 2.79s. The renderer computes its crossfade
    # offsets from the exact beat duration, so a short clip stalls the stitch.
    frame_count = max(4, int(round(duration * src_fps)) + 2)

    # Cost is per generated frame, so it is knowable before spending anything.
    # ~$0.00003/frame on gemini-2.5-flash-image puts a full 3-beat ~11s reel
    # near $0.003, or ~$0.006 if a beat needs the amplified retry. Under the
    # default free-only policy none of this is spent: the ladder check below
    # refuses every rung first.
    if not billing.filter_ladder(
        [n.strip() for n in os.environ.get("FRAME_PROVIDER_ORDER", DEFAULT_FRAME_ORDER).split(",") if n.strip()],
        FRAME_LADDER,
        "frame diffusion",
    ):
        raise FrameDiffusionError(
            "frame diffusion is disabled by the free-only billing policy "
            "(all of its models are paid); no credit was spent"
        )

    est = frame_count * 0.00003 * int(os.environ.get("FRAME_ATTEMPTS", "2"))
    log(f"  [fd] budget: ~{frame_count} frames x up to {os.environ.get('FRAME_ATTEMPTS', '2')} "
        f"attempts = ~${est:.4f} for this beat")

    workdir = out_path + ".frames"
    os.makedirs(workdir, exist_ok=True)

    try:
        # Two attempts. A re-anchored image chain sometimes animates too
        # gently to clear the motion gate, and the correct response is to ask
        # for a bigger physical change - not to relax the gate, which would
        # let the motionless camera-pan fallback pass as live motion.
        attempts = int(os.environ.get("FRAME_ATTEMPTS", "2"))
        best: tuple[float, str] | None = None

        for attempt in range(1, attempts + 1):
            amplify = attempt > 1
            if amplify:
                log(f"  [fd] first chain animated too gently - retrying with amplified motion")

            for name in os.listdir(workdir):
                try:
                    os.remove(os.path.join(workdir, name))
                except OSError:
                    pass

            _generate_chain(img_path, motion_prompt, workdir, frame_count, seed + attempt * 7919, log, amplify)

            # Optical-flow interpolation is what turns 8 deliberate frames per
            # second into something that reads as smooth video rather than a
            # flipbook. It also hides the small inconsistencies between
            # independently generated frames.
            # Interpolation filter ladder.
            #
            # The first rung (motion-compensated bidirectional optical flow) is
            # the best-looking but the least portable. On CI's ffmpeg 6.1.1 it
            # died with "Invalid data found when processing input" / "Error
            # marking filters as finished" at EOF - a known minterpolate
            # failure mode with aobmc + bidir. That single filter failure threw
            # away ~100 correctly generated frames per reel, i.e. the frames
            # we had already paid for.
            #
            # So each rung is a progressively more conservative interpolation,
            # and the first that produces a playable file wins. Plain `fps`
            # cannot fail on motion data at all, which guarantees the chain is
            # never wasted.
            for filter_label, interp in INTERPOLATION_LADDER:
                vf = (
                    f"{interp.format(fps=OUTPUT_FPS)},"
                    f"scale=720:1280:force_original_aspect_ratio=increase,crop=720:1280,"
                    f"setsar=1,format=yuv420p"
                )
                proc = _run([
                    FFMPEG_BIN, "-y", "-v", "error",
                    "-framerate", str(src_fps),
                    "-i", os.path.join(workdir, "f%04d.jpg"),
                    "-t", str(duration),
                    "-vf", vf,
                    "-an", "-c:v", "libx264", "-preset", "fast", "-crf", "20",
                    out_path,
                ], timeout=900)

                if proc.returncode == 0 and os.path.exists(out_path) and os.path.getsize(out_path) > 10_000:
                    if filter_label != "mci":
                        log(f"  [fd] interpolation fell back to '{filter_label}' "
                            f"(richer optical-flow modes are unavailable on this ffmpeg)")
                    break

                tail = (proc.stderr or "").strip().splitlines()
                log(f"  [fd] interpolation '{filter_label}' failed: {tail[-1][:150] if tail else 'unknown'}")
            else:
                raise FrameDiffusionError(
                    f"every interpolation mode failed; last error: {tail[-1][:200] if tail else 'unknown'}"
                )

            size = os.path.getsize(out_path)
            if size < 10_000:
                raise FrameDiffusionError(f"interpolated clip is truncated ({size} bytes)")

            # Measure our own output. Reusing the shared gate here means the
            # provider and the renderer can never disagree about whether the
            # character actually moved.
            from src.motion import measure_motion, MOTION_THRESHOLD

            motion = measure_motion(out_path)
            log(
                f"  [fd] attempt {attempt}: {frame_count} frames, motion {motion:.2f} "
                f"(live >= {MOTION_THRESHOLD})"
            )

            if best is None or motion > best[0]:
                best = (motion, out_path + ".best.mp4")
                try:
                    if os.path.exists(best[1]):
                        os.remove(best[1])
                    import shutil

                    shutil.copy(out_path, best[1])
                except OSError:
                    best = (motion, out_path)

            if motion >= MOTION_THRESHOLD:
                break

        if best is None:
            raise FrameDiffusionError("no frames were generated")

        motion, source = best
        from src.motion import MOTION_THRESHOLD, validate_clip

        if motion < MOTION_THRESHOLD:
            ok, reason = validate_clip(source if source != out_path else out_path)
            raise FrameDiffusionError(
                f"animated too gently: best motion {motion:.2f} < {MOTION_THRESHOLD} ({reason})"
            )

        if source != out_path:
            import shutil

            shutil.copy(source, out_path)
            try:
                os.remove(source)
            except OSError:
                pass

        log(f"  [fd] wrote {out_path} ({os.path.getsize(out_path) // 1024} KB, motion {motion:.2f})")
        return out_path

    finally:
        for name in os.listdir(workdir) if os.path.isdir(workdir) else []:
            try:
                os.remove(os.path.join(workdir, name))
            except OSError:
                pass
        try:
            os.rmdir(workdir)
        except OSError:
            pass


def model_label() -> str:
    order = os.environ.get("FRAME_PROVIDER_ORDER", DEFAULT_FRAME_ORDER)
    key = order.split(",")[0].strip()
    return FRAME_LADDER.get(key, key)
